describe('фильтр мата', () => {
  it.each(BAD)('ловит «%s»', (w) => expect(hasProfanity(w)).toBe(true));
  it.each(GOOD)('пропускает «%s»', (w) => expect(hasProfanity(w)).toBe(false));

  it('в чате заменяет только плохие слова', () => {
    expect(censor('ну ты и сука, конечно')).toBe('ну ты и *** конечно');
    expect(censor('Привет, бойцы!')).toBe('Привет, бойцы!');
    expect(censor('вот х у й тебе')).toBe('вот *** тебе');
    expect(censor('страховка за 3 рубля')).toBe('страховка за 3 рубля');
  });

  it('названия проверяет и склеенными', () => {
    expect(badName('Хуй Ло')).toBe(true);
    expect(badName('ПИЗ ДЕЦ')).toBe(true);
    expect(badName('Железные спины')).toBe(false);
    expect(badName('ЖС')).toBe(false);
    expect(badName('Искра')).toBe(false);
    expect(badName('Психуй-ка')).toBe(false);
    expect(badName('Команда А')).toBe(false);
  });
});
