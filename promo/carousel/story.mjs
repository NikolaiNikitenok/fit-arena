export function pickSparks(k = 3, rnd = Math.random) {
  const a = [...STORY_SPARKS];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a.slice(0, k);
}
