export const say = (npc: NpcId, text: string): Line => ({ who: NPCS[npc].name, text, face: npc, color: NPCS[npc].color });

const bossFace = (land: number): string => {
  const L = LANDS[land];
  if (L.world === 'castle') return 'knyaz';
  if (L.world === 'space') return 'boss-1';
  const mage = land % 3 === 2 ? 'm' : '';
  return L.world === 'zombie' ? `boss-2${mage}` : `boss-0${mage}`;
};
export const bossSay = (land: number, text: string): Line => ({ who: LANDS[land].boss.name, text, face: bossFace(land), color: LANDS[land].boss.color });

