export interface StoryKey {
  id: number;
  world: number;
  land: number;
  num: number;
  pos: number;
  type: MissionType;
  rest: boolean;
}

/** Диалог перед уровнем. */
export function storyFor({ id, world, land, num, pos, type, rest }: StoryKey): Line[] {
  const L = LANDS[land];
  const guide = guideOf(world);
  const lines: Line[] = [];
  if (id === 1) lines.push(...PROLOGUE);
  // Вступление земли — на первом уровне земли (в новом мире это первое испытание).
  if (pos === 0 || world === 3) {
    lines.push(say(guide, L.intro), ...LAND_LINES[land].enter);
  }
  if (type === 'trial') {
    if (id !== 1) lines.push(...(num === 1 ? TRIAL_LINES[world] : [say(guide, 'Следующее упражнение. Так же: сколько сможешь, без надрыва.')]));
    return lines;
  }
  if (type === 'boss') {
    lines.push(say(guide, world === 3 ? 'Всё, чему ты научился в трёх мирах, — сейчас.' : `Впереди хранитель этой земли — ${L.boss.name}.`), bossSay(land, L.boss.intro));
    return lines;
  }
  if (rest) {
    const [npc, text] = REST_LINES[world];
    lines.push(say(npc, text));
  } else {
    const [npc, text] = MISSION_LINES[type][world];
    lines.push(say(npc, text));
  }
  return lines;
}

/** Что говорит побеждённый хранитель. */
export function bossDefeat(land: number): Line[] {
  const lines = [bossSay(land, LAND_LINES[land].defeat)];
  if (LANDS[land].world === 'castle')
    lines.push(
      say('grom', 'Это моя вина, ученик. Я не давал тебе отдыхать. Давай начнём сначала, по-другому.'),
      bossSay(land, 'По-другому… С отдыхом? Ладно. Но завтра. Сегодня я и правда устал.'),
      say('lisa', 'Ну всё, теперь вас двое. А я, кажется, тоже теперь бегаю по утрам. Никому не говорите.'),
    );
  return lines;
}

