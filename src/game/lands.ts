export type World = 'fantasy' | 'space' | 'zombie' | 'castle';

export const WORLDS: World[] = ['fantasy', 'space', 'zombie'];

export const WORLD_NAMES: Record<World, string> = {
  fantasy: 'Королевство Атлетия',
  space: 'Космос',
  zombie: 'Зомби-город',
  castle: 'Замок Князя',
};

export interface Land {
  world: World;
  name: string;
  // Цвета земли на карте и в сценах миссий.
  ground: string;
  accent: string;
  sky: string;
  fog: string;
  boss: { name: string; color: string; scale: number; intro: string };
  intro: string;
}

type Row = [name: string, ground: string, accent: string, sky: string, intro: string, boss: string, bossColor: string, bossIntro: string];

const make = (world: World, rows: Row[]): Land[] =>
  rows.map(([name, ground, accent, sky, intro, boss, color, bossIntro], i) => ({
    world,
    name,
    ground,
    accent,
    sky,
    fog: sky,
    intro,
    boss: { name: boss, color, scale: 1.5 + i * 0.08, intro: bossIntro },
  }));

