/** Пул фраз по времени суток: утром и вечером чаще звучат «свои» фразы. */
function pool(d) {
  const h = d.getHours();
  if (h >= 5 && h < 11) return [...PHRASES, ...MORNING, ...MORNING];
  if (h >= 18 && h < 24) return [...PHRASES, ...EVENING, ...EVENING];
  if (h < 5) return [...NIGHT, ...NIGHT, ...PHRASES.slice(0, 20)];
  return PHRASES;
}

/** Простое детерминированное «перемешивание»: одна и та же фраза для одного и того же ключа. */
function pick(key, list = PHRASES) {
  let h = 2166136261;
  for (let i = 0; i < key.length; i++) h = Math.imul(h ^ key.charCodeAt(i), 16777619);
  return list[(h >>> 0) % list.length];
}

const pad = (n) => String(n).padStart(2, '0');
const dayKey = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

export const phraseOfDay = (d = new Date()) => pick('day:' + dayKey(d));
export const phraseOfHour = (d = new Date()) => {
  // Фраза часа не совпадает с фразой дня.
  const list = pool(d);
  let p = pick(`hour:${dayKey(d)}:${d.getHours()}`, list);
  if (p === phraseOfDay(d)) p = pick(`hour2:${dayKey(d)}:${d.getHours()}`, list);
  return p;
};
export const randomPhrase = () => { const l = pool(new Date()); return l[Math.floor(Math.random() * l.length)]; };
